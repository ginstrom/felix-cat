// Run with Node.js after editing the checked-in English manual HTML.
// The original Sphinx source files are unavailable, so index the published pages.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const manual = path.join(__dirname, '..');
const searchTools = fs.readFileSync(path.join(__dirname, 'searchtools.js'), 'utf8');
const context = {
  jQuery: {},
  $: () => ({ ready() {} }),
  document: {},
};
vm.runInNewContext(searchTools, context);
const stemmer = new context.Stemmer();

function article(html) {
  const body = html.split('<div class="body">')[1];
  return body?.split('<div class="sidebar">')[0] ?? '';
}

function pageText(html) {
  return html.replace(/<a class="headerlink"[^>]*>.*?<\/a>/gs, '')
    .replace(/<[^>]*>/g, ' ').replace(/&[\w#]+;/g, ' ');
}

// Follow links from the live table of contents, avoiding duplicate legacy pages
// and navigation text shared by every page.
const pages = new Map();
const pending = ['index.html'];
for (const filename of pending) {
  if (pages.has(filename) || ['genindex.html', 'search.html'].includes(filename)) continue;
  const file = path.join(manual, filename);
  if (!fs.existsSync(file)) continue;
  const body = article(fs.readFileSync(file, 'utf8'));
  const heading = body.match(/<h1\b[^>]*>(.*?)<\/h1>/s);
  if (!heading) continue;
  const title = heading[1].replace(/<a class="headerlink"[^>]*>.*?<\/a>/gs, '').replace(/<[^>]*>/g, '').trim();
  pages.set(filename, { title, text: pageText(body) });
  for (const link of body.matchAll(/<a\b[^>]*\bhref="([^"#?]+\.html)(?:[?#][^"]*)?"/g)) {
    const target = path.posix.normalize(path.posix.join(path.posix.dirname(filename), link[1]));
    if (!/^(?:\/|\.\.\/)|:/.test(target)) pending.push(target);
  }
}

const filenames = [...pages.keys()].sort();
const titles = [];
const terms = Object.create(null);
for (const [index, filename] of filenames.entries()) {
  const page = pages.get(filename);
  titles.push(page.title);
  const words = page.text.toLowerCase().match(/[\p{L}\d_]+(?:[-'][\p{L}\d_]+)*/gu) ?? [];
  const stems = new Set(words.flatMap(word => [word, ...word.split(/[-']/)]).map(word => stemmer.stemWord(word)));
  for (const stem of stems) {
    if (!terms[stem]) terms[stem] = [];
    terms[stem].push(index);
  }
}

const sortedTerms = Object.fromEntries(Object.keys(terms).sort().map(term => [term, terms[term]]));
const searchIndex = { filenames: filenames.map(name => name.slice(0, -5)), titles, terms: sortedTerms, objects: {}, objnames: {} };
const output = '// Generated by _static/build-search-index.cjs.\nSearch.setIndex(' + JSON.stringify(searchIndex) + ');\n';
fs.writeFileSync(path.join(manual, 'searchindex.js'), output);
console.log(`Indexed ${pages.size} English manual pages.`);
